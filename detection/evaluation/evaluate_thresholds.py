"""Sweeps the composite-score threshold against ground-truth fraud labels and
reports precision / recall / false-positive rate at each point, plus the chosen
operating threshold. Outputs a CSV of the full curve, a PNG plot, and a markdown
summary consumed by the README's metrics table.

Run standalone, or as the Airflow task `compute_pipeline_metrics` (see
airflow/dags/aml_pipeline_dag.py).
"""

import time
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd
from sqlalchemy import text

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from detection.db import get_engine

REPORTS_DIR = Path(__file__).resolve().parent / "reports"
METRICS_DOC_PATH = Path(__file__).resolve().parent.parent.parent / "docs" / "metrics" / "latest_evaluation_report.md"
CHOSEN_THRESHOLD = 0.60  # the "high" severity boundary -- see combine_scores.SEVERITY_THRESHOLDS

ALERTS_QUERY = """
select composite_score, is_fraud_label
from detection.alerts
"""

TOTAL_FRAUD_QUERY = """
select count(*) as total_fraud
from raw_marts_core.fact_transactions
where is_fraud_label
"""

TOTAL_TXNS_QUERY = "select count(*) as total from raw_marts_core.fact_transactions"


def load_eval_data():
    engine = get_engine()
    with engine.connect() as conn:
        alerts = pd.read_sql(text(ALERTS_QUERY), conn)
        total_fraud = pd.read_sql(text(TOTAL_FRAUD_QUERY), conn)["total_fraud"].iloc[0]
        total_txns = pd.read_sql(text(TOTAL_TXNS_QUERY), conn)["total"].iloc[0]
    return alerts, int(total_fraud), int(total_txns)


def sweep_thresholds(alerts: pd.DataFrame, total_fraud: int, total_txns: int) -> pd.DataFrame:
    thresholds = np.round(np.arange(0.05, 1.01, 0.05), 2)
    rows = []
    for t in thresholds:
        flagged = alerts[alerts["composite_score"] >= t]
        n_flagged = len(flagged)
        true_positives = int(flagged["is_fraud_label"].sum())
        false_positives = n_flagged - true_positives

        precision = true_positives / n_flagged if n_flagged else 0.0
        recall = true_positives / total_fraud if total_fraud else 0.0
        fp_rate = false_positives / total_txns if total_txns else 0.0

        rows.append(
            {
                "threshold": t,
                "alerts_flagged": n_flagged,
                "true_positives": true_positives,
                "false_positives": false_positives,
                "precision": round(precision, 4),
                "recall": round(recall, 4),
                "fp_rate": round(fp_rate, 6),
            }
        )
    return pd.DataFrame(rows)


def plot_curve(curve: pd.DataFrame, output_path: Path) -> None:
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.5))

    ax1.plot(curve["recall"], curve["precision"], marker="o", color="#2b6cb0")
    ax1.set_xlabel("Recall")
    ax1.set_ylabel("Precision")
    ax1.set_title("Precision vs. Recall")
    ax1.grid(alpha=0.3)

    ax2.plot(curve["threshold"], curve["fp_rate"], marker="o", label="FP rate", color="#c53030")
    ax2.plot(curve["threshold"], curve["recall"], marker="s", label="Recall", color="#2f855a")
    ax2.set_xlabel("Composite score threshold")
    ax2.set_ylabel("Rate")
    ax2.set_title("FP Rate & Recall vs. Threshold")
    ax2.legend()
    ax2.grid(alpha=0.3)

    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=120)
    plt.close(fig)


def write_markdown_report(curve: pd.DataFrame, chosen_row: pd.Series, total_fraud: int, total_txns: int) -> None:
    METRICS_DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Detection evaluation report",
        "",
        "Generated by `detection/evaluation/evaluate_thresholds.py`. All data is synthetic "
        "(see `data/sample/DATA_DICTIONARY.md`).",
        "",
        f"- Rows processed: **{total_txns:,}**",
        f"- Ground-truth fraud transactions: **{total_fraud:,}**",
        f"- Chosen operating threshold (composite score): **{CHOSEN_THRESHOLD}**",
        f"- Precision at chosen threshold: **{chosen_row['precision']:.2%}**",
        f"- Recall at chosen threshold: **{chosen_row['recall']:.2%}**",
        f"- False-positive rate at chosen threshold: **{chosen_row['fp_rate']:.3%}**",
        f"- Alerts generated at chosen threshold: **{int(chosen_row['alerts_flagged']):,}**",
        "",
        "## Full threshold sweep",
        "",
        "| Threshold | Alerts | True Positives | Precision | Recall | FP Rate |",
        "|---|---|---|---|---|---|",
    ]
    for _, r in curve.iterrows():
        lines.append(
            f"| {r['threshold']} | {int(r['alerts_flagged']):,} | {int(r['true_positives']):,} "
            f"| {r['precision']:.2%} | {r['recall']:.2%} | {r['fp_rate']:.3%} |"
        )
    lines += [
        "",
        "![Precision/recall and FP-rate curves](threshold_curve.png)",
        "",
    ]
    METRICS_DOC_PATH.write_text("\n".join(lines))


PIPELINE_RUNS_SCHEMA = """
create schema if not exists pipeline_state;

create table if not exists pipeline_state.pipeline_runs (
    run_id serial primary key,
    run_at timestamp not null default now(),
    rows_processed int not null,
    alerts_generated int not null,
    precision_at_threshold numeric(6, 4) not null,
    recall_at_threshold numeric(6, 4) not null,
    fp_rate_at_threshold numeric(8, 6) not null,
    runtime_seconds numeric(8, 2) not null,
    ge_status varchar(16) not null
);
"""


def record_pipeline_run(total_txns: int, alerts_generated: int, chosen_row: pd.Series, runtime_seconds: float) -> None:
    engine = get_engine()
    with engine.begin() as conn:
        conn.execute(text(PIPELINE_RUNS_SCHEMA))
        conn.execute(
            text(
                """
                insert into pipeline_state.pipeline_runs
                    (rows_processed, alerts_generated, precision_at_threshold,
                     recall_at_threshold, fp_rate_at_threshold, runtime_seconds, ge_status)
                values
                    (:rows_processed, :alerts_generated, :precision, :recall, :fp_rate, :runtime, 'passed')
                """
            ),
            {
                "rows_processed": total_txns,
                "alerts_generated": alerts_generated,
                "precision": float(chosen_row["precision"]),
                "recall": float(chosen_row["recall"]),
                "fp_rate": float(chosen_row["fp_rate"]),
                "runtime": round(runtime_seconds, 2),
            },
        )


def main() -> dict:
    start = time.time()
    alerts, total_fraud, total_txns = load_eval_data()
    if alerts.empty:
        print("No alerts found -- run detection/run_detection.py first.")
        return {}

    curve = sweep_thresholds(alerts, total_fraud, total_txns)
    curve.to_csv(REPORTS_DIR / "threshold_curve.csv", index=False)
    plot_curve(curve, REPORTS_DIR / "threshold_curve.png")
    # Also committed alongside the markdown report so the chart renders on GitHub
    # without anyone having to run the pipeline first.
    plot_curve(curve, METRICS_DOC_PATH.parent / "threshold_curve.png")

    chosen_row = curve.iloc[(curve["threshold"] - CHOSEN_THRESHOLD).abs().idxmin()]
    write_markdown_report(curve, chosen_row, total_fraud, total_txns)
    record_pipeline_run(total_txns, len(alerts), chosen_row, time.time() - start)

    print(curve.to_string(index=False))
    print(f"\nChosen threshold={CHOSEN_THRESHOLD}: "
          f"precision={chosen_row['precision']:.2%} recall={chosen_row['recall']:.2%} "
          f"fp_rate={chosen_row['fp_rate']:.3%}")
    return chosen_row.to_dict()


if __name__ == "__main__":
    main()
